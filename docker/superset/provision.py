"""Registers the analytics database and imports the versioned dashboard bundle (idempotent).

Runs on every start of the Superset container (see bootstrap.sh):

1. Creates or updates the "MeLi Trends (PostgreSQL)" connection with the credentials from
   the environment, keeping the UUID the bundle refers to.
2. Imports the bundle in /app/meli_dashboard (generated by superset/build_dashboard.py)
   when the dashboard does not exist yet, so dashboards come back even on a new volume.
   With SUPERSET_DASHBOARDS_IMPORT=overwrite (or --overwrite) the bundle replaces the
   dashboard, its charts and dataset, e.g. after updating the bundle in the repository.
3. Stores the filter scopes (charts and tabs each dashboard filter applies to) and the
   cross-filter scopes of the charts, as the dashboard editor does when a dashboard is saved.
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import sys
import uuid
from pathlib import Path
from urllib.parse import quote

import yaml

BUNDLE_DIR = Path(os.environ.get("MELI_DASHBOARD_BUNDLE", "/app/meli_dashboard"))
log = logging.getLogger("meli-provision")


def analytics_uri() -> str:
    return "postgresql+psycopg2://{user}:{password}@{host}:{port}/{db}".format(
        user=quote(os.environ["ANALYTICS_DB_USER"], safe=""),
        password=quote(os.environ["ANALYTICS_DB_PASSWORD"], safe=""),
        host=os.environ["ANALYTICS_DB_HOST"],
        port=os.environ["ANALYTICS_DB_PORT"],
        db=os.environ["ANALYTICS_DB_NAME"],
    )


def read_bundle() -> dict[str, str]:
    files = {str(p.relative_to(BUNDLE_DIR)): p.read_text(encoding="utf-8") for p in BUNDLE_DIR.rglob("*.yaml")}
    if "metadata.yaml" not in files:
        raise FileNotFoundError(f"No dashboard bundle in {BUNDLE_DIR}")
    return files


def single(files: dict[str, str], prefix: str) -> tuple[str, dict]:
    matches = [(name, yaml.safe_load(text)) for name, text in files.items() if name.startswith(prefix)]
    if len(matches) != 1:
        raise ValueError(f"Expected one {prefix} file in the bundle, found {len(matches)}")
    return matches[0]


def chart_scopes(position: dict, native_filters: list[dict]) -> None:
    """Fill chartsInScope / tabsInScope of every filter from its scope (rootPath + excluded)."""
    charts = {
        item["meta"]["chartId"]: item
        for item in position.values()
        if isinstance(item, dict) and item.get("type") == "CHART"
    }

    def tab_of(item: dict) -> str | None:
        tabs = [p for p in item.get("parents", []) if p.startswith("TAB-")]
        return tabs[-1] if tabs else None

    for native_filter in native_filters:
        excluded = set(native_filter.get("scope", {}).get("excluded", []))
        in_scope = [chart_id for chart_id in charts if chart_id not in excluded]
        native_filter["chartsInScope"] = in_scope
        native_filter["tabsInScope"] = sorted({t for c in in_scope if (t := tab_of(charts[c]))})


def chart_ids_by_uuid(position: dict) -> dict[str, int]:
    return {
        item["meta"]["uuid"]: item["meta"]["chartId"]
        for item in position.values()
        if isinstance(item, dict) and item.get("type") == "CHART"
    }


def cross_filter_scopes(bundle_position: dict, position: dict, chart_configuration: dict) -> dict:
    """Map the bundle's per-chart cross-filter scopes to the imported chart ids and fill their
    chartsInScope. The importer remaps native filter scopes but leaves chart_configuration with
    the placeholder ids of the bundle."""
    imported = chart_ids_by_uuid(position)
    id_map = {old: imported[u] for u, old in chart_ids_by_uuid(bundle_position).items() if u in imported}
    chart_ids = list(imported.values())
    fixed = {}
    for old_id, config in chart_configuration.items():
        chart_id = id_map.get(int(old_id))
        if chart_id is None:
            continue
        scope = config["crossFilters"]["scope"]
        excluded = {id_map[c] for c in scope.get("excluded", []) if c in id_map}
        fixed[str(chart_id)] = {
            "id": chart_id,
            "crossFilters": {
                "scope": {**scope, "excluded": sorted(excluded)},
                "chartsInScope": [c for c in chart_ids if c != chart_id and c not in excluded],
            },
        }
    return fixed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--overwrite", action="store_true", help="re-import the bundle over existing assets")
    args = parser.parse_args()
    overwrite = args.overwrite or os.environ.get("SUPERSET_DASHBOARDS_IMPORT", "missing").lower() == "overwrite"

    files = read_bundle()
    database_file, database_config = single(files, "databases/")
    _, dashboard_config = single(files, "dashboards/")
    database_uuid = uuid.UUID(str(database_config["uuid"]))
    dashboard_uuid = uuid.UUID(str(dashboard_config["uuid"]))
    database_name = database_config["database_name"]

    from superset.app import create_app

    app = create_app()
    with app.app_context():
        from flask import g

        from superset import db, security_manager
        from superset.commands.importers.v1.assets import ImportAssetsCommand
        from superset.models.core import Database
        from superset.models.dashboard import Dashboard

        g.user = security_manager.find_user(username=os.environ["SUPERSET_ADMIN_USERNAME"])
        if g.user is None:
            log.error("Admin user %s not found", os.environ["SUPERSET_ADMIN_USERNAME"])
            return 1

        def register_database() -> None:
            database = (
                db.session.query(Database).filter_by(uuid=database_uuid).one_or_none()
                or db.session.query(Database).filter_by(database_name=database_name).one_or_none()
            )
            if database is None:
                database = Database(database_name=database_name, uuid=database_uuid)
                db.session.add(database)
            database.uuid = database_uuid
            database.database_name = database_name
            database.expose_in_sqllab = True
            database.set_sqlalchemy_uri(analytics_uri())
            db.session.commit()

        register_database()
        log.info("Database connection %r is registered", database_name)

        exists = db.session.query(Dashboard).filter_by(uuid=dashboard_uuid).one_or_none() is not None
        if exists and not overwrite:
            log.info("Dashboard %r already exists; keeping it as it is", dashboard_config["dashboard_title"])
            return 0

        ImportAssetsCommand(files, passwords={database_file: os.environ["ANALYTICS_DB_PASSWORD"]}).run()
        register_database()  # the bundle carries the default connection string; restore the real one

        dashboard = db.session.query(Dashboard).filter_by(uuid=dashboard_uuid).one()
        metadata = json.loads(dashboard.json_metadata or "{}")
        position = json.loads(dashboard.position_json or "{}")
        chart_scopes(position, metadata.get("native_filter_configuration", []))
        metadata["chart_configuration"] = cross_filter_scopes(
            dashboard_config["position"], position, metadata.get("chart_configuration", {})
        )
        chart_ids =[item["meta"]["chartId"] for item in position.values() if isinstance(item, dict) and item.get("type") == "CHART"]
        metadata["global_chart_configuration"] = {
            "scope": {"rootPath": ["ROOT_ID"], "excluded": []},
            "chartsInScope": chart_ids,
        }
        dashboard.json_metadata = json.dumps(metadata)
        db.session.commit()
        log.info(
            "Imported dashboard %r with %s charts (%s)",
            dashboard.dashboard_title,
            len(chart_ids),
            "overwrite" if exists else "new",
        )
    return 0


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    sys.exit(main())
